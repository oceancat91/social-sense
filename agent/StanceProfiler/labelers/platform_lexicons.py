def get_platform_lexicon(platform: str | None) -> dict[str, list[str]]:
    """返回平台专属词表；未知平台返回空词表。"""
    return PLATFORM_LEXICONS.get((platform or "").lower(), {})


def get_platform_markers(platform: str | None) -> list[str]:
    """返回平台圈层标记词/梗（无明确极性的黑话）。"""
    return list(get_platform_lexicon(platform).get("markers", []))


def merge_lexicon(base: dict[str, list[str]], extra: dict[str, list[str]]) -> dict[str, list[str]]:
    """合并通用词表与平台专属词表（去重保序）。"""
    merged: dict[str, list[str]] = {}
    for key in ("support_cues", "oppose_cues", "pos_sent", "neg_sent"):
        seen: set[str] = set()
        acc: list[str] = []
        for w in list(base.get(key, [])) + list(extra.get(key, [])):
            if w and w not in seen:
                seen.add(w)
                acc.append(w)
        merged[key] = acc
    return merged
